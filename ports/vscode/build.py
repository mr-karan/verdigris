def setting(style) -> dict:
    """A token setting. An empty fontStyle resets what a broader rule set."""
    return {"foreground": style.color, "fontStyle": textmate.font_style(style)}


def token_colors(f) -> list:
    return [
        {"name": label, "scope": scopes, "settings": setting(style)}
        for label, scopes, style in textmate.rules(f)
    ]


def semantic_tokens(f) -> dict:
    syntax = f.syntax
    roles = {
        "comment": "comment", "keyword": "keyword", "string": "string", "number": "number",
        "regexp": "regex", "operator": "operator", "namespace": "namespace",
        "type": "type", "class": "type", "struct": "type", "enum": "type", "interface": "type",
        "typeParameter": "type", "builtinType": "type", "typeAlias": "type",
        "enumMember": "constant", "boolean": "constant",
        "function": "function", "method": "function",
        "macro": "decorator", "decorator": "decorator", "attributeBracket": "decorator",
        "parameter": "parameter", "variable": "variable", "property": "property",
        "selfKeyword": "builtin", "selfParameter": "builtin", "selfTypeKeyword": "builtin",
        "label": "label", "lifetime": "label",
        "escapeSequence": "escape", "formatSpecifier": "escape",
    }
    tokens = {selector: setting(syntax[role]) for selector, role in roles.items()}
    tokens["*.deprecated"] = {"strikethrough": True}
    tokens["unresolvedReference"] = {"foreground": f["cuprite"]}
    return tokens


def theme(f) -> str:
    document = {
        "$schema": "vscode://schemas/color-theme",
        "name": f.title,
        "type": f.appearance,
        "semanticHighlighting": True,
        "colors": workbench(f),
        "tokenColors": token_colors(f),
        "semanticTokenColors": semantic_tokens(f),
    }
    return json.dumps(document, indent=2) + "\n"



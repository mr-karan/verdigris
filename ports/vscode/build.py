def render(palette) -> dict:
    files = {f"themes/{f.slug}-color-theme.json": theme(f) for f in palette.flavours.values()}
    files["package.json"] = manifest(palette)
    # vsce packages the extension directory, so it carries its own licence.
    files["LICENSE"] = (ROOT / "LICENSE").read_text()
    files[".vscodeignore"] = "build.py\n__pycache__/\n"
    return files
